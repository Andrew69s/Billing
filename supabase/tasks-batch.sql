-- =========================================================
--  Задачі, поставлені одразу кільком (createTasks({assignees:[...]})),
--  зберігаються як окремий рядок на кожного отримувача — тому в списку
--  того, хто поставив, одна й та сама задача дублювалась N разів
--  (по одному рядку на магазин). Додаємо спільний batch_id, яким
--  клієнт групує такі рядки в одну картку.
-- =========================================================
alter table public.tasks add column if not exists batch_id uuid;
create index if not exists tasks_batch_id_idx on public.tasks (batch_id) where batch_id is not null;
